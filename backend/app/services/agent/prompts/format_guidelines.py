"""
输出格式指导模块

定义 AI 输出的格式规范，让回复更加丰富、清晰
"""


# 通用格式指导（插入到 System Prompt 中）
OUTPUT_FORMAT_GUIDELINES = """
## 【必须遵守】输出格式规范

你的回复**必须**使用以下格式，这是强制要求：

### 1. 状态和评价【必须用 Emoji】
- ✅ 推荐、正确、完成、优点
- ❌ 不推荐、错误、失败、缺点
- ⚠️ 警告、注意、风险
- 💡 提示、建议、灵感
- 📌 重点、关键、核心
- 🎯 目标、结论、要点

### 2. 对比分析【必须用表格】
当分析优缺点、对比选项时，**必须**使用表格：

| 维度 | 评价 | 说明 |
|-----|-----|-----|
| 节奏 | ✅ 优秀 | 张弛有度 |
| 人物 | ⚠️ 一般 | 刻画略浅 |

### 3. 流程和因果【必须用箭头】
- 原因 → 结果
- 问题 → 分析 → 解决方案
- 输入 → 处理 → 输出

### 4. 重点提示【必须用引用块】
> 💡 **关键点**：这里是重要信息

### 5. 结构化列表
- 📚 内容分析类
- 🔧 技术问题类
- 🎯 结论建议类

### 6. 禁止的格式
❌ 禁止纯文字大段落
❌ 禁止不带emoji的列表
❌ 禁止不用表格的对比分析
"""


# 简化版格式指导（增强版）
OUTPUT_FORMAT_GUIDELINES_LITE = """
## 【必须遵守】格式规范

**强制要求**：
1. 评价用 ✅/❌/⚠️/💡 emoji
2. 对比分析**必须**用表格
3. 因果关系用 → 箭头
4. 重点用 > 引用块 + 💡

**示例**：
| 维度 | 评价 | 说明 |
|-----|-----|-----|
| 节奏 | ✅ | 张弛有度 |

> 💡 **关键**：这是重点信息

❌ 禁止：纯文字大段落、无emoji列表
"""


def get_format_guidelines(lite: bool = False) -> str:
    """
    获取格式指导文本

    Args:
        lite: 是否使用简化版（节省 token）

    Returns:
        格式指导文本
    """
    return OUTPUT_FORMAT_GUIDELINES_LITE if lite else OUTPUT_FORMAT_GUIDELINES
