"""
输出格式指导模块

定义 AI 输出的格式规范，让回复更加丰富、清晰
"""


# 通用格式指导（插入到 System Prompt 中）
OUTPUT_FORMAT_GUIDELINES = """
## 【必须遵守】输出格式规范

你的回复**必须**使用以下格式，这是强制要求：

### 1. 层级标题【必须用Markdown标题】
回复内容较长时，**必须**使用Markdown标题组织结构：
- `## 标题` 用于主要章节（如：## 分析结果、## 修改建议）
- `### 标题` 用于子章节（如：### 人物塑造、### 情节节奏）

示例：
## 📝 详细说明
这里是详细说明的内容...

### 💡 关键点
这里是关键点内容...

### 2. 状态和评价【必须用 Emoji】
- ✅ 推荐、正确、完成、优点
- ❌ 不推荐、错误、失败、缺点
- ⚠️ 警告、注意、风险
- 💡 提示、建议、灵感
- 📌 重点、关键、核心
- 🎯 目标、结论、要点

### 3. 对比分析【必须用表格】
当分析优缺点、对比选项时，**必须**使用表格：

| 维度 | 评价 | 说明 |
|-----|-----|-----|
| 节奏 | ✅ 优秀 | 张弛有度 |
| 人物 | ⚠️ 一般 | 刻画略浅 |

### 4. 流程和因果【必须用箭头】
- 原因 → 结果
- 问题 → 分析 → 解决方案
- 输入 → 处理 → 输出

### 5. 重点提示【必须用引用块】
> 💡 **关键点**：这里是重要信息

### 6. 结构化列表【必须用 Markdown 列表语法】

#### 6.1 无序列表（并列要点）
- 📚 内容分析类
- 🔧 技术问题类
- 🎯 结论建议类

#### 6.2 有序列表（步骤/流程/排名）
当内容有顺序、步骤或优先级时，**必须**使用编号列表：
1. 第一步：分析问题
2. 第二步：制定方案
3. 第三步：执行修改

#### 6.3 任务列表（完成状态）
标记任务完成状态时，使用任务列表语法：
- [x] 已完成的任务
- [ ] 待完成的任务

#### 6.4 嵌套列表（层级结构）
复杂内容使用嵌套列表，层次分明：
1. 主要修改点
   - 子项说明 A
   - 子项说明 B
2. 次要修改点
   - 详细描述

示例：
## 📝 修改结果总结
1. **赵穆出场描写扩写**: 对赵穆的描写进行了扩写
   - 增加了外貌细节描写
   - 补充了动作神态
2. **段融内息萌动**: 添加了内息萌动的描写
3. **三人对话个性化**: 赋予更具个性化的语言风格

### 6.5 润色/改写要点格式【必须遵守】
润色或改写完成后，描述修改要点时**必须**使用以下格式：
- 每个修改要点**必须**以 `- ` 开头（Markdown列表语法）
- 每个要点的标题用**加粗**
- 修改说明用冒号分隔

✅ 正确格式示例：
## ✨ 润色要点
- **"暗骂"表达优化**：将"段融暗骂了句"改为"段融心头暗骂一句"，使其更偏向内心活动。
- **"马粪味"描写生动化**：将"一身马粪味，臭死了！"改为通过他人反应和嗅觉感受来描绘，例如"一股浓郁的马厩气味便弥漫开来"。
- **赵穆出场描写具象化**：将"人长得五大三粗"改为"他脖颈粗壮，下颌方正，裸露的小臂上青筋盘错如老树盘根"。

❌ 错误格式（禁止）：
🟢"暗骂"表达优化：将...（没有用 `- ` 开头）
"暗骂"表达优化：将...（没有列表符号）

### 7. 禁止的格式
❌ 禁止纯文字大段落（必须用标题分隔）
❌ 禁止不用 `- ` 开头的列表（必须用Markdown列表语法）
❌ 禁止不带emoji的列表
❌ 禁止不用表格的对比分析
"""


# 简化版格式指导（增强版）
OUTPUT_FORMAT_GUIDELINES_LITE = """
## 【必须遵守】格式规范

**强制要求**：
1. **层级标题**：内容较长时必须用 `## 标题` 和 `### 子标题` 组织结构
2. **列表格式**：
   - 并列要点用 `- ` 无序列表
   - 步骤/流程用 `1. 2. 3.` 编号列表
   - 完成状态用 `- [x]` 和 `- [ ]` 任务列表
   - 复杂内容用嵌套列表（缩进3空格）
3. 评价用 ✅/❌/⚠️/💡 emoji
4. 对比分析**必须**用表格
5. 因果关系用 → 箭头
6. 重点用 > 引用块 + 💡

**示例**：
## 📝 修改结果总结
1. **赵穆出场描写扩写**: 对赵穆的描写进行了扩写
   - 增加了外貌细节描写
   - 补充了动作神态
2. **段融内息萌动**: 添加了内息萌动的描写
3. **三人对话个性化**: 赋予更具个性化的语言风格

## ✅ 完成情况
- [x] 人物描写优化
- [x] 对话个性化
- [ ] 场景氛围渲染

### 💡 关键点
| 维度 | 评价 | 说明 |
|-----|-----|-----|
| 节奏 | ✅ | 张弛有度 |

> 💡 **关键**：这是重点信息

❌ 禁止：纯文字大段落、不用列表语法的列举
"""


def get_format_guidelines(lite: bool = False) -> str:
    """
    获取格式指导文本

    Args:
        lite: 是否使用简化版（节省 token）

    Returns:
        格式指导文本
    """
    return OUTPUT_FORMAT_GUIDELINES_LITE if lite else OUTPUT_FORMAT_GUIDELINES
