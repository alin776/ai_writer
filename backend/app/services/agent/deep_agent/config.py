"""DeepAgent 配置常量

基于 LangChain Deep Agents 设计理念，提供反思和重规划的配置项。

🔧 2025-12-08: 重构
- 反思触发机制改为基于 AI 标记的 checkpoint 字段
- 移除了基于关键词的触发条件（不够准确）
- 保留任务失败时的兜底反思
"""

# 🔧 2025-12-08: 移除了 List 导入（不再需要 REPLAN_KEYWORDS）


class DeepAgentConfig:
    """DeepAgent 配置

    核心设计：
    - AI 在 Planning 阶段标记 checkpoint: true 的任务
    - 执行时只在 checkpoint 任务完成后触发反思
    - 这样让 AI 决定何时反思，而不是用规则判断
    """

    # ════════════════════════════════════════════════════════════════
    # 反思限制
    # ════════════════════════════════════════════════════════════════
    MAX_REFLECTIONS: int = 3      # 单次请求最多反思次数
    MAX_REPLANS: int = 2          # 单次请求最多重规划次数

    # ════════════════════════════════════════════════════════════════
    # 超时设置（秒）
    # ════════════════════════════════════════════════════════════════
    REFLECTION_TIMEOUT: int = 30  # 反思超时
    REPLAN_TIMEOUT: int = 45      # 重规划超时

    # ════════════════════════════════════════════════════════════════
    # 反思触发条件
    # ════════════════════════════════════════════════════════════════
    # 主要触发条件：task.checkpoint == True（由 AI 在规划阶段标记）
    # 兜底触发条件：任务失败时反思
    REFLECT_ON_FAILURE: bool = True  # 任务失败时触发反思（兜底机制）

    # ════════════════════════════════════════════════════════════════
    # 重规划判断
    # ════════════════════════════════════════════════════════════════
    # 🔧 2025-12-08: 移除 REPLAN_KEYWORDS 硬编码
    # 现在使用标记式输出格式：AI 在反思第一行输出 REPLAN:YES 或 REPLAN:NO
    # 解析逻辑在 reflection.py 的 _parse_reflection_response() 中
