"""DeepAgent 配置常量

基于 LangChain Deep Agents 设计理念，提供反思和重规划的配置项。

🔧 2025-12-08: 重构
- 反思触发机制改为基于 AI 标记的 checkpoint 字段
- 移除了基于关键词的触发条件（不够准确）
- 保留任务失败时的兜底反思

🔧 2025-12-13: 性能优化
- 添加 NON_CRITICAL_TOOLS 配置，定义不需要重规划的工具
- 减少不必要的反思和重规划，降低Token消耗
"""

# 🔧 2025-12-08: 移除了 List 导入（不再需要 REPLAN_KEYWORDS）


class DeepAgentConfig:
    """DeepAgent 配置

    核心设计：
    - AI 在 Planning 阶段标记 checkpoint: true 的任务
    - 执行时只在 checkpoint 任务完成后触发反思
    - 这样让 AI 决定何时反思，而不是用规则判断
    """

    # ════════════════════════════════════════════════════════════════
    # 反思限制
    # ════════════════════════════════════════════════════════════════
    MAX_REFLECTIONS: int = 3      # 单次请求最多反思次数
    MAX_REPLANS: int = 2          # 单次请求最多重规划次数

    # ════════════════════════════════════════════════════════════════
    # 超时设置（秒）
    # ════════════════════════════════════════════════════════════════
    REFLECTION_TIMEOUT: int = 30  # 反思超时
    REPLAN_TIMEOUT: int = 45      # 重规划超时

    # ════════════════════════════════════════════════════════════════
    # 反思触发条件
    # ════════════════════════════════════════════════════════════════
    # 主要触发条件：task.checkpoint == True（由 AI 在规划阶段标记）
    # 兜底触发条件1：任务失败时反思
    REFLECT_ON_FAILURE: bool = True  # 任务失败时触发反思（兜底机制）
    # 兜底触发条件2：规划未标记任何checkpoint时，首个任务执行后强制一次反思（校验规划质量）
    REFLECT_ON_FIRST_TASK_IF_NO_CHECKPOINT: bool = True

    # 🔧 2025-12-11: 已移除的触发条件（代码中不再使用）
    # - REFLECT_ON_MISSING_CHECKPOINT（间隔触发）
    # - MISSING_CHECKPOINT_INTERVAL（每N个任务触发）
    # - 分析类/写作类任务自动触发
    # - 短任务链倒数第二步触发

    # ════════════════════════════════════════════════════════════════
    # 重规划判断
    # ════════════════════════════════════════════════════════════════
    # 🔧 2025-12-08: 移除 REPLAN_KEYWORDS 硬编码
    # 现在使用标记式输出格式：AI 在反思第一行输出 REPLAN:YES 或 REPLAN:NO
    # 解析逻辑在 reflection.py 的 _parse_reflection_response() 中

    # ════════════════════════════════════════════════════════════════
    # 🔧 2025-12-13: 非关键工具配置（性能优化）
    # 🔧 2025-12-16: 仅保留纯输入类工具，分析类工具需要能触发重规划
    # ════════════════════════════════════════════════════════════════
    # 这些工具即使反思认为needs_replan=true，也会被执行器跳过重规划
    # 原因：这些都是纯输入类工具，只是获取数据，不涉及质量判断
    NON_CRITICAL_TOOLS: set = {
        # 输入类工具（获取数据）- 数据获取成功就行，不需要重规划
        "get_context_tool",              # 获取作品上下文
        "search_analysis_fragments_tool", # 检索章节片段
        "search_content",               # 搜索章节片段（snippet）
        "read_chapter_tool",             # 读取章节内容
        "get_chapter_by_order_tool",     # 按序号获取章节
        # 注：分析类工具（analyze_text_tool, evaluate_quality_tool等）不在此列表
        # 因为分析结果是主观的，质量可能不达标，需要保留重规划机会
    }
