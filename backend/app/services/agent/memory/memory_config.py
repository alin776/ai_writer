"""
Memory 配置集中管理

将 memory 模块的阈值/超时集中在此，避免在各处硬编码。
与 context_config.py 风格一致。

2025-12-09: 初始创建，收敛散落的配置项
"""


class MemoryConfig:
    """Memory 模块配置常量"""

    # ════════════════════════════════════════════════════════════════
    # TTL 配置（秒）
    # ════════════════════════════════════════════════════════════════
    SHORT_TERM_TTL: int = 86400           # 短期记忆 24小时
    MEDIUM_TERM_TTL: int = 86400 * 3      # 中期记忆 3天
    SNAPSHOT_TTL: int = 86400 * 7         # 快照 7天
    VERSION_TTL: int = 86400 * 30         # 版本保留 30天

    # ════════════════════════════════════════════════════════════════
    # 容量限制
    # ════════════════════════════════════════════════════════════════
    MAX_VERSIONS: int = 50                # 每用户最大版本数
    COMPRESS_THRESHOLD: int = 10000       # 压缩阈值（字符数）
    LONG_TERM_MAX_SIZE_KB: int = 50       # 长期记忆二次压缩阈值（KB）

    # ════════════════════════════════════════════════════════════════
    # 锁超时配置（秒）
    # ════════════════════════════════════════════════════════════════
    LOCK_TIMEOUT: int = 30                # 分布式锁超时
    LOCK_BLOCKING_TIMEOUT: int = 5        # 锁等待超时

    # ════════════════════════════════════════════════════════════════
    # 遗忘策略 - 时间衰减参数
    # ════════════════════════════════════════════════════════════════
    DECAY_HALF_LIFE_DAYS: float = 7.0     # 半衰期（天）
    MAX_RETENTION_DAYS: int = 90          # 最大保留天数

    # ════════════════════════════════════════════════════════════════
    # 遗忘策略 - 重要度阈值
    # ════════════════════════════════════════════════════════════════
    CRITICAL_IMPORTANCE: float = 0.9      # 关键重要度（不遗忘）
    HIGH_IMPORTANCE: float = 0.7          # 高重要度（降低遗忘率）
    MEDIUM_IMPORTANCE: float = 0.5        # 中等重要度

    # ════════════════════════════════════════════════════════════════
    # 遗忘策略 - 访问频率参数
    # ════════════════════════════════════════════════════════════════
    ACCESS_BOOST_FACTOR: float = 0.1      # 每次访问的提升
    MAX_ACCESS_BOOST: float = 0.5         # 最大访问提升

    # ════════════════════════════════════════════════════════════════
    # 遗忘策略 - 关联性参数
    # ════════════════════════════════════════════════════════════════
    LINK_PROTECTION_FACTOR: float = 0.05  # 每个关联的保护值
    MAX_LINK_PROTECTION: float = 0.3      # 最大关联保护

    # ════════════════════════════════════════════════════════════════
    # 遗忘策略 - 遗忘阶段阈值
    # ════════════════════════════════════════════════════════════════
    FADING_THRESHOLD: float = 0.3         # 进入褪色阶段
    DORMANT_THRESHOLD: float = 0.5        # 进入休眠阶段
    ARCHIVED_THRESHOLD: float = 0.7       # 进入归档阶段
    FORGOTTEN_THRESHOLD: float = 0.85     # 进入遗忘阶段

    # ════════════════════════════════════════════════════════════════
    # 遗忘策略 - 批量遗忘参数
    # ════════════════════════════════════════════════════════════════
    MIN_RETENTION_COUNT: int = 10         # 最少保留记忆数
    MAX_FORGET_PER_BATCH: int = 20        # 每批最多遗忘数
