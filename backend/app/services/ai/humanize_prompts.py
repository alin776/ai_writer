# ========== 辅助函数 ==========

def _format_detected_patterns_section(detected_patterns: Optional[List[str]]) -> str:
    """格式化检测到的AI痕迹部分"""
    if not detected_patterns:
        return ""

    patterns_list = "\n".join([f"   - {p}" for p in detected_patterns])
    return f"""
**⚠️ 检测到的具体AI痕迹（必须重点处理）：**
{patterns_list}

请特别针对上述检测到的痕迹进行修改！这些是本文最明显的AI特征。
"""


def get_humanize_prompt(
    text: str,
    intensity: Literal["light", "medium", "strong"] = "medium",
    detected_patterns: Optional[List[str]] = None
) -> str:
    """
    获取去痕迹 Prompt

    Args:
        text: 待去痕迹的文本
        intensity: 强度 (light/medium/strong)
        detected_patterns: 检测到的AI痕迹列表（可选，传入后会针对性处理）

    Returns:
        完整的 Prompt
    """
    prompt_map = {
        "light": HUMANIZE_LIGHT_PROMPT,
        "medium": HUMANIZE_MEDIUM_PROMPT,
        "strong": HUMANIZE_STRONG_PROMPT
    }

    template = prompt_map.get(intensity, HUMANIZE_MEDIUM_PROMPT)

    # 格式化检测到的痕迹部分
    detected_patterns_section = _format_detected_patterns_section(detected_patterns)

    return template.format(
        text=text,
        detected_patterns_section=detected_patterns_section
    )


def get_detection_prompt(text: str) -> str:
    """获取检测 Prompt"""
    return DETECTION_PROMPT.format(text=text)


def get_verification_prompt(original_text: str, humanized_text: str) -> str:
    """获取验证 Prompt"""
    return VERIFICATION_PROMPT.format(
        original_text=original_text,
        humanized_text=humanized_text
    )
